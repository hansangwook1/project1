-- 기능 1. 음식 찜 테이블 (이미 만들었다면 건너뜀)
USE food_allergy_db;

CREATE TABLE IF NOT EXISTS FAVORITES (
    ID          BIGINT       NOT NULL AUTO_INCREMENT,
    USER_ID     BIGINT       NOT NULL,
    FOOD_CODE   VARCHAR(50)  NOT NULL,
    FOOD_NAME   VARCHAR(200) NOT NULL,
    CREATED_AT  DATETIME(6)  NOT NULL,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_FAVORITES_USER_FOOD (USER_ID, FOOD_CODE),   -- 같은 회원이 같은 음식을 두 번 찜할 수 없음
    CONSTRAINT FK_FAVORITES_USER FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID)
);

CREATE TABLE IF NOT EXISTS REVIEWS (
    ID          BIGINT       NOT NULL AUTO_INCREMENT,
    USER_ID     BIGINT       NOT NULL,
    FOOD_CODE   VARCHAR(50)  NOT NULL,
    CONTENT     VARCHAR(500) NOT NULL,
    CREATED_AT  DATETIME(6)  NOT NULL,
    UPDATED_AT  DATETIME(6)  NULL,
    PRIMARY KEY (ID),
    KEY IDX_REVIEWS_FOOD_CODE (FOOD_CODE),     -- 음식별 리뷰 조회를 빠르게
    CONSTRAINT FK_REVIEWS_USER FOREIGN KEY (USER_ID) REFERENCES USERS (USER_ID)
);
